"""Facts about the target's own code that discovery reports (no AI, no execution).

ADR 0004: comments that switch checks off (D4), code static analysis can't see
into (D5), and which files each tool examined (D3); with them, the near-duplicate
functions from `similar`, which the file review can't see one file at a time. Every output depends only on
the files and the scan outputs, so a re-run on the same snapshot is identical (C4).
"""

from __future__ import annotations

import json
import os
import re
from pathlib import Path, PurePosixPath
from typing import Any

from audit_kit import similar
from audit_kit.errors import WorkspaceError
from audit_kit.inventory import Inventory
from audit_kit.unused import JS, analyse, strip_comments
from audit_kit.workspace import Workspace

SUPPRESSIONS = ".audit/scans/suppressions.json"
BLINDSPOTS = ".audit/scans/blindspots.json"
COVERAGE = ".audit/scans/coverage.json"
SWEEP = ".audit/scans/sweep.json"
LINT = ".audit/scans/lint.json"
TSC_FILES = ".audit/scans/typecheck-files.txt"
CODE = (*JS, ".ts", ".tsx", ".jsx", ".mts", ".cts", ".html", ".htm", ".vue", ".svelte")
HTML = (".html", ".htm")
MAX_BYTES = 5_000_000

# A directive counts only right after a comment marker, so prose about one doesn't.
DIRECTIVE = re.compile(
    r"(?://|/\*|<!--|^[ \t]*\*|#)[ \t]*"
    r"(?P<d>eslint-disable(?:-next-line|-line)?|@ts-ignore|@ts-expect-error|@ts-nocheck"
    r"|nosemgrep|gitleaks:allow|istanbul ignore|c8 ignore|NOSONAR)\b(?P<rest>[^\n]*)",
    re.M,
)
# Code built from strings at run time; eval of a literal is still a blind spot.
STRING_CODE = re.compile(
    r"\b(?P<k>eval)\s*\(|\bnew\s+(?P<f>Function)\s*\("
    r"|\bset(?:Timeout|Interval)\s*\(\s*(?P<t>['\"`])"
)
# The sweep runs on every class, vendored and minified included (ADR 0004 D2).
# Each hit is a lead for review, not a finding.
SWEEP_KINDS = {
    "code from strings": STRING_CODE,
    "child_process": re.compile(
        r"""(?:require\(\s*|from\s+)['"](?:node:)?child_process['"]"""
    ),
    "vm": re.compile(r"""(?:require\(\s*|from\s+)['"](?:node:)?vm['"]"""),
    "network": re.compile(
        r"\bfetch\s*\(|\bXMLHttpRequest\b|\bnew\s+WebSocket\s*\(|\bhttps?\.(?:request|get)\s*\("
        r"|\bnavigator\.sendBeacon\s*\("
        r"""|(?:require\(\s*|from\s+)['"](?:node:)?(?:net|tls|dgram)['"]"""
    ),
    "file write": re.compile(
        r"\bfs(?:\.promises)?\.(?:write|append)File(?:Sync)?\s*\(|\bcreateWriteStream\s*\("
    ),
    "bulk environment read": re.compile(
        r"JSON\.stringify\(\s*process\.env\s*\)|Object\.(?:keys|entries|values)\(\s*process\.env\s*\)"
        r"|\.\.\.process\.env\b"
    ),
    "browser storage read": re.compile(
        r"\bdocument\.cookie\b|\b(?:local|session)Storage\.getItem\s*\("
    ),
    "long encoded string": re.compile(
        r"""['"`](?:[A-Za-z0-9+/]{200,}={0,2}|(?:[0-9a-fA-F]{2}){100,})['"`]"""
    ),
}
GENERATED_HEADER = re.compile(
    r"auto-?generated|do not (?:edit|modify)|generated by|@generated", re.I
)
SWEPT = (*JS, ".ts", ".tsx", ".jsx", ".mts", ".cts", ".html", ".htm", ".vue", ".svelte")
SWEEP_SHOWN = 5
SWEEP_BYTES = 16_000_000
INLINE_SCRIPT = re.compile(r"<script\b(?![^>]*\bsrc\s*=)[^>]*>\s*\S", re.I)
TOOLS_NOT_REPORTING = {
    "semgrep": "sast.sarif lists results, not the files scanned",
    "jscpd": "duplication.json lists clones, not the files read",
    "gitleaks": "secrets.json lists leaks, not the files read",
}


def _line(text: str, offset: int) -> int:
    return text.count("\n", 0, offset) + 1


def _kept(path: str, excluded: tuple[str, ...]) -> bool:
    return not any(path == e or path.startswith(e.rstrip("/") + "/") for e in excluded)


def _own(
    inv: Inventory, excluded: tuple[str, ...], suffixes: tuple[str, ...]
) -> list[str]:
    return sorted(
        e.path
        for e in inv.of("own")
        if e.kind == "file" and e.path.endswith(suffixes) and _kept(e.path, excluded)
    )


def _read(ws: Workspace, path: str, problems: list[str]) -> str | None:
    try:
        return ws.read_text(path, limit=MAX_BYTES)
    except WorkspaceError as exc:
        problems.append(f"not read: {exc}")
        return None


def _directive(name: str, rest: str) -> tuple[list[str], str]:
    """Split what follows a directive into the rules it names and its reason."""
    rest = re.sub(r"\s*(?:\*/|-->)\s*$", "", rest).strip()
    if name.startswith("eslint-disable"):
        rules, _, reason = rest.partition("--")
        named = [r.strip() for r in rules.split(",") if r.strip()]
        return named or ["all"], reason.strip()
    if name == "nosemgrep":
        m = re.match(r":\s*([\w.,-]+)\s*(.*)", rest)
        return ([*m.group(1).split(",")], m.group(2)) if m else (["all"], rest)
    if name in ("istanbul ignore", "c8 ignore"):
        scope, _, reason = rest.partition(" ")
        return [scope or "next"], reason.lstrip(":- ").strip()
    return ["all"], rest.lstrip(":- ").strip()


def suppressions(
    ws: Workspace, inv: Inventory, excluded: tuple[str, ...]
) -> dict[str, Any]:
    """List every comment in own code that switches a check off (ADR 0004 D4)."""
    entries: list[dict[str, Any]] = []
    problems: list[str] = []
    for path in _own(inv, excluded, CODE):
        text = _read(ws, path, problems)
        for m in DIRECTIVE.finditer(text or ""):
            rules, reason = _directive(m.group("d"), m.group("rest"))
            entries.append(
                {
                    "file": path,
                    "line": _line(text or "", m.start("d")),
                    "directive": m.group("d"),
                    "rules": rules,
                    "reason": reason[:200],
                    "has_reason": bool(re.search(r"[A-Za-z]{3}", reason)),
                }
            )
    return {
        "generated_by": "kit scan: suppression inventory (deterministic, no execution)",
        "counts": {
            "directives": len(entries),
            "without_reason": sum(not e["has_reason"] for e in entries),
        },
        "problems": problems,
        "entries": entries,
    }


def blind_spots(
    ws: Workspace, inv: Inventory, excluded: tuple[str, ...]
) -> dict[str, Any]:
    """List code static analysis can't see into, never treated as safe (D5)."""
    found = analyse(ws, inv, excluded)
    entries = [{"kind": "dynamic import", **d} for d in found["dynamic_requires"]] + [
        {"kind": "unresolved import", **d} for d in found["unresolved_imports"]
    ]
    problems: list[str] = []
    for path in _own(inv, excluded, (*JS, *HTML)):
        raw = _read(ws, path, problems)
        if raw is None:
            continue
        text = raw if path.endswith(HTML) else strip_comments(raw)
        lines = text.splitlines()
        for m in STRING_CODE.finditer(text):
            line = _line(text, m.start())
            kind = (
                "eval"
                if m.group("k")
                else "new Function"
                if m.group("f")
                else "string timer"
            )
            entries.append(
                {
                    "kind": kind,
                    "file": path,
                    "line": line,
                    "text": lines[line - 1].strip()[:100],
                }
            )
    entries.sort(key=lambda e: (e["file"], e["line"], e["kind"]))
    counts: dict[str, int] = {}
    for e in entries:
        counts[e["kind"]] = counts.get(e["kind"], 0) + 1
    return {
        "generated_by": "kit scan: blind spots (deterministic, no execution)",
        "meaning": "Static analysis can't see what this code loads or runs. Never safe by default.",
        "counts": dict(sorted(counts.items())),
        "problems": problems,
        "entries": entries,
    }


def _examined(
    ws: Workspace, rel: str, tool: str, expected: list[str]
) -> set[str] | None:
    """Return the expected paths a tool says it examined, or None if unreadable.

    Tools write absolute paths for the machine the scan ran on. A copied or moved
    workspace has another root, so a path outside this root is matched to the
    expected file with the longest common tail (`admin/auth.js` before `auth.js`).
    """
    if not ws.is_file(rel):
        return None
    try:
        text = ws.read_text(rel, limit=500_000_000)
        raw = json.loads(text) if tool == "eslint" else text.splitlines()
    except (WorkspaceError, json.JSONDecodeError):
        return None
    if not isinstance(raw, list):
        return None
    names = [
        str(r.get("filePath", "")) if isinstance(r, dict) else str(r)
        for r in raw
        if tool != "eslint" or isinstance(r, dict)
    ]
    return set(match_tool_paths(ws.root, names, set(expected)).values())


def match_tool_paths(root: Path, names: list[str], wanted: set[str]) -> dict[str, str]:
    """Map the paths a tool wrote to wanted paths relative to the target.

    Tools write absolute paths for the machine the scan ran on. A copied or moved
    workspace has another root, so a path outside this root is matched to the
    wanted file with the longest common tail (`admin/auth.js` before `auth.js`).

    Returns:
        {path as the tool wrote it: relative path}, for wanted paths only.
    """
    real = os.path.realpath(root)
    found: dict[str, str] = {}
    for name in (n.strip() for n in names if n.strip()):
        full = os.path.realpath(Path(root) / name)
        if full.startswith(real + os.sep):
            rel = Path(full).relative_to(real).as_posix()
            if rel in wanted:
                found[name] = rel
            continue
        parts = PurePosixPath(Path(name).as_posix()).parts
        tail = next(
            (t for i in range(1, len(parts)) if (t := "/".join(parts[i:])) in wanted),
            None,
        )
        if tail:
            found[name] = tail
    return found


def coverage(
    ws: Workspace, inv: Inventory, excluded: tuple[str, ...]
) -> dict[str, Any]:
    """Record, per own file and tool, whether the tool examined it (D3)."""
    expected = _own(inv, excluded, JS)
    gaps: list[dict[str, str]] = []
    tools: dict[str, dict[str, Any]] = {}
    for tool, rel in (("eslint", LINT), ("tsc", TSC_FILES)):
        seen = _examined(ws, rel, tool, expected)
        if seen is None:
            tools[tool] = {"status": "no usable output", "expected": len(expected)}
            gaps += [
                {"file": p, "tool": tool, "reason": f"{rel} missing or unreadable"}
                for p in expected
            ]
            continue
        missed = [p for p in expected if p not in seen]
        tools[tool] = {
            "status": "ran",
            "expected": len(expected),
            "examined": len(expected) - len(missed),
        }
        gaps += [
            {"file": p, "tool": tool, "reason": "the tool didn't report it"}
            for p in missed
        ]
    for tool, why in TOOLS_NOT_REPORTING.items():
        tools[tool] = {"status": "not reported", "why": why}
    problems: list[str] = []
    for path in _own(inv, excluded, HTML):
        text = _read(ws, path, problems)
        if text and INLINE_SCRIPT.search(text):
            gaps.append(
                {
                    "file": path,
                    "tool": "eslint, tsc",
                    "reason": "inline <script> not checked by any tool",
                }
            )
    gaps.sort(key=lambda g: (g["file"], g["tool"]))
    return {
        "generated_by": "kit scan: coverage per file and tool (deterministic)",
        "tools": tools,
        "counts": {"gaps": len(gaps)},
        "problems": problems,
        "gaps": gaps,
    }


def sweep(ws: Workspace, inv: Inventory) -> dict[str, Any]:
    """Look for dangerous calls in every text file, whatever its class (D2).

    A vendored file that makes network calls or runs strings as code is a lead
    for the supply-chain review. Up to five hits per file and kind are listed;
    the counts include all of them.
    """
    entries: list[dict[str, Any]] = []
    counts: dict[str, dict[str, int]] = {}
    problems: list[str] = []
    files = [
        e
        for e in inv.entries
        if e.kind == "file" and not e.binary and e.path.endswith(SWEPT)
    ]
    for e in files:
        text = _read_swept(ws, e.path, problems)
        if text is None:
            continue
        lines = text.splitlines()
        if e.cls == "own" and GENERATED_HEADER.search("\n".join(lines[:10])):
            entries.append(_hit(e.cls, e.path, text, 0, "generated claim", lines))
            _count(counts, e.cls, "generated claim")
        kinds: dict[str, set[str]] = {}
        for kind, pattern in SWEEP_KINDS.items():
            hits = list(pattern.finditer(text))
            for m in hits[:SWEEP_SHOWN]:
                entries.append(_hit(e.cls, e.path, text, m.start(), kind, lines))
            if hits:
                kinds.setdefault(kind, set()).add(e.path)
                _count(counts, e.cls, kind, len(hits))
        if "browser storage read" in kinds and "network" in kinds:
            entries.append(
                _hit(
                    e.cls,
                    e.path,
                    text,
                    0,
                    "storage read and network call in one file",
                    lines,
                )
            )
            _count(counts, e.cls, "storage read and network call in one file")
    entries.sort(key=lambda h: (h["file"], h["line"], h["kind"]))
    return {
        "generated_by": "kit scan: sweep of every text file (deterministic, no execution)",
        "meaning": (
            "Leads, not findings. Vendored, generated and minified files are swept too, "
            "because a folder name doesn't prove a file is what it claims. gitleaks "
            "already scans the whole tree, vendored folders included."
        ),
        "files_swept": len(files),
        "counts": {cls: dict(sorted(k.items())) for cls, k in sorted(counts.items())},
        "problems": problems,
        "entries": entries,
    }


def _read_swept(ws: Workspace, path: str, problems: list[str]) -> str | None:
    try:
        return ws.read_text(path, limit=SWEEP_BYTES)
    except WorkspaceError as exc:
        problems.append(f"not swept: {exc}")
        return None


def _count(counts: dict[str, dict[str, int]], cls: str, kind: str, n: int = 1) -> None:
    by_kind = counts.setdefault(cls, {})
    by_kind[kind] = by_kind.get(kind, 0) + n


def _hit(
    cls: str, path: str, text: str, offset: int, kind: str, lines: list[str]
) -> dict[str, Any]:
    """One sweep hit: a short window around it, so minified lines stay readable."""
    line = _line(text, offset)
    start = text.rfind("\n", 0, offset) + 1
    column = offset - start + 1
    source = lines[line - 1] if line <= len(lines) else ""
    window = source[max(0, column - 40) : column + 80].strip()
    return {
        "class": cls,
        "file": path,
        "line": line,
        "column": column,
        "kind": kind,
        "text": window,
    }


def write_all(
    ws: Workspace, inv: Inventory, excluded: tuple[str, ...]
) -> dict[str, int]:
    """Write the five fact files; returns the headline count for each."""
    out = {
        SWEEP: sweep(ws, inv),
        SUPPRESSIONS: suppressions(ws, inv, excluded),
        BLINDSPOTS: blind_spots(ws, inv, excluded),
        COVERAGE: coverage(ws, inv, excluded),
        similar.OUTPUT: similar.report(ws, inv, excluded),
    }
    for rel, body in out.items():
        ws.write_text(rel, json.dumps(body, indent=1) + "\n")
    swept = out[SWEEP]["counts"]
    return {
        "sweep hits outside own code": sum(
            n for cls, kinds in swept.items() if cls != "own" for n in kinds.values()
        ),
        "suppressions without a reason": out[SUPPRESSIONS]["counts"]["without_reason"],
        "blind spots": len(out[BLINDSPOTS]["entries"]),
        "coverage gaps": out[COVERAGE]["counts"]["gaps"],
        "near-duplicate functions": out[similar.OUTPUT]["counts"]["pairs"],
    }
